/**
 * Writes the headers and redirects from config/headers.ts for each host (D44):
 *   out/_headers, out/_redirects        Cloudflare Pages, Netlify
 *   deploy/vercel.json                  Vercel
 *   deploy/nginx/security-headers.conf  Nginx (include inside the server block)
 * Runs after `next build` (see package.json "build").
 */
import { existsSync, mkdirSync, rmSync, writeFileSync } from 'node:fs';
import { join } from 'node:path';
import { fileURLToPath } from 'node:url';
import { CACHE_RULES, REDIRECTS, securityHeaders, type Header } from '../config/headers';
import { siteEnv } from '../src/lib/env';

const root = fileURLToPath(new URL('..', import.meta.url));
const outDir = join(root, 'out');
const deployDir = join(root, 'deploy');
const env = siteEnv();

function headersFile(): string {
  const block = (path: string, headers: Header[]) =>
    [path, ...headers.map(([k, v]) => `  ${k}: ${v}`)].join('\n');
  return (
    [block('/*', securityHeaders(env)), ...CACHE_RULES.map((r) => block(r.path, r.headers))].join(
      '\n\n',
    ) + '\n'
  );
}

function redirectsFile(): string {
  return REDIRECTS.map((r) => `${r.from} ${r.to} ${r.status}`).join('\n') + '\n';
}

function vercelConfig(): string {
  const toVercel = (headers: Header[]) => headers.map(([key, value]) => ({ key, value }));
  return (
    JSON.stringify(
      {
        headers: [
          { source: '/(.*)', headers: toVercel(securityHeaders(env)) },
          ...CACHE_RULES.map((r) => ({
            source: r.path.replace('*', '(.*)'),
            headers: toVercel(r.headers),
          })),
        ],
        redirects: REDIRECTS.map((r) => ({
          source: r.from,
          destination: r.to,
          permanent: r.status === 301,
        })),
      },
      null,
      2,
    ) + '\n'
  );
}

function nginxConf(): string {
  const lines = securityHeaders(env).map(([k, v]) => `add_header ${k} "${v}" always;`);
  const redirects = REDIRECTS.map((r) => `location = ${r.from} { return ${r.status} ${r.to}; }`);
  return (
    [
      `# Generated by scripts/emit-headers.ts (SITE_ENV=${env}). Do not edit.`,
      ...lines,
      '',
      ...redirects,
    ].join('\n') + '\n'
  );
}

if (!existsSync(outDir)) {
  console.error('✗ out/ not found. Run `next build` first.');
  process.exit(1);
}
mkdirSync(join(deployDir, 'nginx'), { recursive: true });
// M2 review pages (D53) never ship to production or the demo: remove them so they are real 404s.
if (env === 'production' || env === 'demo') {
  rmSync(join(outDir, 'lab'), { recursive: true, force: true });
}

writeFileSync(join(outDir, '_headers'), headersFile());
writeFileSync(join(outDir, '_redirects'), redirectsFile());
writeFileSync(join(deployDir, 'vercel.json'), vercelConfig());
// The demo is hosted on Vercel (D83): Vercel reads vercel.json from the project root before
// it builds, so the demo build keeps the committed copy in step (build command, output,
// headers, redirects). Commit it after `npm run build:demo` changes it.
if (env === 'demo') {
  const config = JSON.parse(vercelConfig()) as Record<string, unknown>;
  writeFileSync(
    join(root, 'vercel.json'),
    JSON.stringify(
      {
        $schema: 'https://openapi.vercel.sh/vercel.json',
        framework: null,
        installCommand: 'npm ci',
        buildCommand: 'npm run build:demo',
        outputDirectory: 'out',
        trailingSlash: true,
        ...config,
      },
      null,
      2,
    ) + '\n',
  );
}
writeFileSync(join(deployDir, 'nginx', 'security-headers.conf'), nginxConf());
console.log(
  `✓ Headers and redirects written for SITE_ENV=${env} (out/_headers, out/_redirects, deploy/).`,
);
