/**
 * Client review list (M9, BUILD_PLAN): every flagged value from the content report plus
 * every OPEN_QUESTIONS item that blocks launch, written to docs/CLIENT_REVIEW.md.
 *
 *   npm run review-list              regenerate
 *   npm run review-list -- --check   fail if the committed list is out of date (CI)
 */
import { readFileSync, writeFileSync } from 'node:fs';
import { join } from 'node:path';
import { fileURLToPath } from 'node:url';
import { rawFiles } from '../src/content/raw';
import { flaggedValues } from '../src/content/report';

const root = fileURLToPath(new URL('..', import.meta.url));
const outPath = join(root, 'docs', 'CLIENT_REVIEW.md');

const REASON_TEXT: Record<string, string> = {
  mock: 'placeholder',
  toConfirm: 'to confirm',
  needsVerification: 'to verify',
  addressMissing: 'address missing',
  unconfirmed: 'not yet confirmed',
  estimatedAllergens: 'allergens are estimates (never shown)',
};

/** OPEN_QUESTIONS table rows whose "Blocks" column mentions launch. */
export function launchQuestions(markdown: string): Array<{ id: string; question: string }> {
  const rows: Array<{ id: string; question: string }> = [];
  for (const line of markdown.split('\n')) {
    const cells = line.split('|').map((c) => c.trim());
    // ['', 'Q1', question, why, blocks, '']
    if (cells.length < 6 || !/^Q\d+$/.test(cells[1]!)) continue;
    if (/launch/i.test(cells[cells.length - 2]!)) rows.push({ id: cells[1]!, question: cells[2]! });
  }
  return rows.sort((a, b) => Number(a.id.slice(1)) - Number(b.id.slice(1)));
}

const escape = (s: string) => s.replace(/\|/g, '\\|');

export function renderReviewList(): string {
  const flags = flaggedValues(rawFiles);
  const questions = launchQuestions(readFileSync(join(root, 'docs', 'OPEN_QUESTIONS.md'), 'utf8'));
  const byFile = new Map<string, typeof flags>();
  for (const f of flags) byFile.set(f.file, [...(byFile.get(f.file) ?? []), f]);

  const lines = [
    '# Client review list',
    '',
    '> Generated by `npm run review-list` from the content report and `OPEN_QUESTIONS.md`. Do not edit by hand.',
    '',
    `The site cannot go live until both lists are empty: the production build refuses to run while any value below is flagged. Staging shows the same count in the corner badge (**${flags.length}** values today).`,
    '',
    `## 1. Questions that block launch (${questions.length})`,
    '',
    '| # | Question |',
    '|---|---|',
    ...questions.map((q) => `| ${q.id} | ${escape(q.question)} |`),
    '',
    `## 2. Content to replace or confirm (${flags.length})`,
    '',
  ];
  for (const [file, list] of byFile) {
    lines.push(
      `### \`data/${file}\` (${list.length})`,
      '',
      '| Where | What | Why |',
      '|---|---|---|',
    );
    for (const f of list) {
      const why = f.reasons.map((r) => REASON_TEXT[r] ?? r).join(', ');
      lines.push(`| \`${f.path}\` | ${escape(f.label ?? '')} | ${why} |`);
    }
    lines.push('');
  }
  lines.push(
    '## 3. Checks to run on staging',
    '',
    'These need real devices, accounts or tools that CI does not have (BUILD_PLAN M8).',
    '',
    '- [ ] Lighthouse mobile on every route: LCP < 2.5 s, CLS < 0.1, TBT < 200 ms',
    "- [ ] Google's Rich Results Test on the Home page (JSON-LD)",
    '- [ ] VoiceOver on iOS and macOS, NVDA on Windows: menu, booking flow, cookie banner',
    '- [ ] 200% browser zoom on every route',
    '- [ ] Safari (macOS, iOS), Firefox and Edge, last two versions; one mid-range Android phone',
    '- [ ] Candle smoothness trace on a mid-range laptop (M2 sign-off)',
    '- [ ] Booking flow on a real phone',
    '',
  );
  return lines.join('\n');
}

const isMain = process.argv[1] && fileURLToPath(import.meta.url) === process.argv[1];
if (isMain) {
  const text = renderReviewList();
  if (process.argv.includes('--check')) {
    const current = readFileSync(outPath, 'utf8');
    if (current !== text) {
      console.error('docs/CLIENT_REVIEW.md is out of date. Run `npm run review-list`.');
      process.exit(1);
    }
    console.log('Client review list is up to date.');
  } else {
    writeFileSync(outPath, text);
    console.log(`✓ docs/CLIENT_REVIEW.md written.`);
  }
}
